// Copies shared/deployments/*.json into src/generated/deployments.ts and the simulator's member and
// supplier CSVs into src/generated/directory.ts, so Metro can bundle them (Metro does not resolve
// files outside the project). Runs before `npm start` and after install.
// Names are off-chain (OPEN-5): the contract only knows addresses.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";

const sourceDir = new URL("../../shared/deployments/", import.meta.url);
const dataDir = new URL("../../simulator/data/", import.meta.url);
const outDir = new URL("../src/generated/", import.meta.url);

// simulator/data/<folder> → chainId
const DATA_FOLDERS = { local: 31337, sepolia: 421614 };

const deployments = {};
try {
  for (const name of await readdir(sourceDir)) {
    if (!name.endsWith(".json")) continue;
    const d = JSON.parse(await readFile(new URL(name, sourceDir), "utf8"));
    deployments[d.chainId] = { address: d.address, chainId: d.chainId, deployBlock: d.deployBlock, params: d.params, abi: d.abi };
  }
} catch {
  // No deployments yet: the app shows a message instead of failing to bundle.
}

/** Same format as simulator/src/csv.ts: header row, comma-separated, `#` lines are comments. */
async function readCsv(url) {
  let text;
  try {
    text = await readFile(url, "utf8");
  } catch {
    return [];
  }
  const lines = text
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l !== "" && !l.startsWith("#"));
  const header = (lines.shift() ?? "").split(",").map((h) => h.trim());
  return lines.map((line) => {
    const cells = line.split(",").map((c) => c.trim());
    return Object.fromEntries(header.map((h, j) => [h, cells[j]]));
  });
}

// chainId → lowercase address → { unit?, name, kind }
const directory = {};
for (const [folder, chainId] of Object.entries(DATA_FOLDERS)) {
  const entries = {};
  for (const r of await readCsv(new URL(`${folder}/members.csv`, dataDir))) {
    if (r.direccion) entries[r.direccion.toLowerCase()] = { unit: r.unidad, name: r.titular, kind: "member" };
  }
  for (const r of await readCsv(new URL(`${folder}/suppliers.csv`, dataDir))) {
    if (r.direccion) entries[r.direccion.toLowerCase()] = { name: r.nombre, kind: "supplier" };
  }
  if (Object.keys(entries).length > 0) directory[chainId] = entries;
}

await mkdir(outDir, { recursive: true });
await writeFile(
  new URL("deployments.ts", outDir),
  "// Generated by scripts/sync-deployments.mjs — do not edit.\n" +
    'import type { Deployment } from "../config";\n\n' +
    `export const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`,
);
await writeFile(
  new URL("directory.ts", outDir),
  "// Generated by scripts/sync-deployments.mjs from simulator/data/<network>/*.csv — do not edit.\n" +
    'import type { DirectoryEntry } from "../directory";\n\n' +
    `export const directory: Record<number, Record<string, DirectoryEntry>> = ${JSON.stringify(directory, null, 2)};\n`,
);
console.log(`Deployments copied for chainId: ${Object.keys(deployments).join(", ") || "(none)"}`);
console.log(`Names copied for chainId: ${Object.keys(directory).join(", ") || "(none)"}`);
